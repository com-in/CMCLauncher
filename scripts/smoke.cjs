const { _electron: electron } = require('playwright');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
(async () => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'craft-ui-'));
  const game = path.join(directory, 'library/instances/fixture');
  await fs.mkdir(path.join(game, 'resourcepacks/Test Pack'), { recursive: true });
  await fs.writeFile(path.join(game, 'resourcepacks/Test Pack/pack.mcmeta'), JSON.stringify({ pack: { pack_format: 34, description: 'UI fixture resource' } }));
  await fs.mkdir(path.join(game, 'mods'), { recursive: true });
  const zip = new (require('adm-zip'))(); zip.addFile('fabric.mod.json', Buffer.from(JSON.stringify({ id: 'ui_mod', name: 'Recognized UI Mod', version: '2.0' }))); zip.writeZip(path.join(game, 'mods/ui.jar'));
  await fs.writeFile(path.join(directory, 'settings.json'), JSON.stringify({ instances: [{ id: 'fixture', name: 'UI Test World', gameVersion: '1.21.1', loader: 'fabric' }] }));
  let app;
  try {
    app = await electron.launch({ ...(process.env.CRAFT_SMOKE_EXECUTABLE ? { executablePath: process.env.CRAFT_SMOKE_EXECUTABLE, args: [] } : { args: [path.resolve(__dirname, '..')] }), env: { ...process.env, CRAFT_TEST_HOME: directory } });
    const page = await app.firstWindow();
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    await page.getByRole('heading', { name: '准备好，进入你的世界。' }).waitFor();
    await page.locator('[data-page=accounts]').click();
    await page.locator('#offline-name').fill('CraftTester');
    await page.getByRole('button', { name: '添加离线账号' }).click();
    await page.locator('.account-info strong').filter({ hasText: 'CraftTester' }).waitFor();
    await page.locator('[data-page=settings]').click();
    await page.locator('#memory').fill('6144');
    await page.locator('#theme').selectOption('light');
    await page.locator('#game-language').selectOption('zh_cn');
    await page.getByRole('button', { name: '保存设置' }).click();
    await page.waitForFunction(async () => (await window.craft.state()).settings.memoryMb === 6144);
    await page.waitForFunction(() => document.documentElement.dataset.theme === 'light');
    await page.locator('[data-page=mods]').click();
    await page.getByText('Recognized UI Mod', { exact: true }).waitFor();
    await page.locator('[data-page=content]').click();
    await page.getByText('UI fixture resource', { exact: true }).waitFor();
    await page.getByRole('button', { name: '停用', exact: true }).click();
    await page.getByRole('button', { name: '恢复', exact: true }).waitFor();
    await page.getByRole('button', { name: '恢复', exact: true }).click();
    await page.getByRole('button', { name: '停用', exact: true }).waitFor();
    await page.locator('[data-type=datapack]').click();
    await page.getByRole('heading', { name: '还没有可以管理的世界' }).waitFor();
    await page.locator('[data-type=shader]').click();
    await page.getByRole('heading', { name: '还没有内容包' }).waitFor();
    await page.locator('[data-page=home]').click();
    await page.getByRole('heading', { name: '准备好，进入你的世界。' }).waitFor();
    await page.locator('#toast').evaluate(el => el.classList.add('hidden'));
    await fs.mkdir('.artifacts', { recursive: true });
    await page.screenshot({ path: '.artifacts/home-light.png' });
    const saved = await page.evaluate(() => window.craft.state());
    if (saved.settings.theme !== 'light' || saved.settings.gameLanguage !== 'zh_cn') throw new Error('New settings did not persist');
    if (saved.accounts[0].name !== 'CraftTester' || errors.length) throw new Error(JSON.stringify({ saved, errors }));
    console.log('PASS: window, navigation, offline account, settings persistence, light theme, metadata recognition, pack toggle, content tabs, screenshot');
  } finally { await app?.close(); await fs.rm(directory, { recursive: true, force: true }); }
})().catch(e => { console.error(e); process.exitCode = 1; });
